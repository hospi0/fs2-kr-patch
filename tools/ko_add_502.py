def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows = [l.rstrip('\n').split('\t') for l in list(open(os.path.join(ROOT, 'work', 'ko_missing.tsv'), encoding='utf-8'))[1:]]
    out = ['ID\t파일\t종류\t원문\t번역\n']; miss = []
    for c in rows:
        i = int(c[0][1:]) if c[0].startswith('X') else None
        if i not in T:
            miss.append(c[0]); continue
        out.append('\t'.join([c[0], c[1], c[2], c[3], T[i]]) + '\n')
    if miss:
        sys.exit('⛔번역 없음 %s' % miss)
    p = os.path.join(ROOT, 'data', 'ko_add.tsv')
    old = list(open(p, encoding='utf-8'))[1:] if os.path.exists(p) else []
    keep = [l for l in old if l.split('\t')[0] not in {c[0] for c in rows}]
    open(p, 'w', encoding='utf-8', newline='').write(out[0] + ''.join(keep) + ''.join(out[1:]))
    print('ko_add.tsv %d줄 추가(기존 %d)' % (len(out) - 1, len(keep)))


if __name__ == '__main__':
    main()
